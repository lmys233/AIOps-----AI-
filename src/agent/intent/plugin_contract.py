"""Replaceable control-plane router extension, independent from telemetry Agents."""
from typing import Any, Protocol


class RoutingPlugin(Protocol):
    async def prepare(self, text: str, slots: Any) -> Any: ...
    async def vector(self, text: str, prepared: Any, slots: Any) -> dict | None: ...
    def allowed(self, prepared: Any) -> set[str]: ...
    def prompt_data(self, prepared: Any) -> list[dict]: ...
