"""判据阈值 —— 「定论 / 再查一轮 / 拒答」这三条边界上的数字。

★ 为什么单独一个模块、而不是塞进 `config.py`：`config.py` 管的是**部署配置**
  （地址、预算、开关，随环境而变）；这里的三个数是**判据**（与部署无关，
  是"证据够不够下定论"的口径），改它们等于改系统行为，必须走评审。
  两类东西的生命周期与责任人都不一样，混在一起迟早会被当成"环境变量"随手改掉。

★★ **全系统唯一定义处**。同一组数字同时服务两个判据，它们回答的是同一个问题
  （"证据够不够下定论"），只是站的位置不同：

    · 终止判据（"这一轮还停不停"）—— 见 `orchestration/state.py::should_terminate`
    · 仲裁判据（"能不能定因 / 要不要定向取证"）—— 见 `attribution/arbiter.py`

  两边各存一份副本的后果实测过：改一处漏另一处，终止判据与仲裁结论会**互相矛盾**
  （例如仲裁认为"候选太接近、需要区分性证据"，而终止判据已按旧数字收口，
  于是流程停下了却拿不到结论 —— 或者反过来，已经能定因了还在空转）。
  所以两边**一律 import 本模块**，谁都不许再写一份同值字面量。

★ 三个数分别回答什么（改之前先回答清楚，否则就是拍脑袋）：

  · `CONFIRM_SCORE` = 0.70：**上界**。"证据够不够定根因"。也是写入长期记忆的
    同一道门槛，两处必须一起改。
  · `TOP2_CLOSE` = 0.15：**可区分性**。softmax 之后 top-1 与 top-2 的差距小于它，
    说明"再多一条区分性证据"就可能翻转排序 —— 应当再查一轮，而不是硬选一个。
  · `ABSTAIN_BELOW` = 0.30：**下界**。"证据是否整体太弱"。8 类候选的 softmax 均分
    约 0.125，0.30 约等于"高于均分一倍多，但仍远离 0.70"，落在"证据太弱"的区间。
"""

from __future__ import annotations

from typing import Final

__all__ = ["CONFIRM_SCORE", "TOP2_CLOSE", "ABSTAIN_BELOW", "METRIC_STALE_SEC"]

#: 确认根因所需的最低分（"最高分 ≥0.70 且未被否决"）
CONFIRM_SCORE: Final[float] = 0.70

#: top-2 分数差小于它就"接近"（需要一条能区分它们的证据）
TOP2_CLOSE: Final[float] = 0.15

#: 低于它算"全部低分"（证据太弱 → 拒答）
ABSTAIN_BELOW: Final[float] = 0.30

#: **读数新鲜度**：最后一次采样距今超过它，就不许把它当成"此刻的读数"。
#: ★ 为什么是判据而不是配置：它决定"能不能说『现在正常』"——与部署环境无关。
#: ★ 实测踩过（把正在报错的服务说成正常）：指标序列的**末点**被当成"当前值"，
#:   而压测结束后指标已回落、序列也停了更新 —— 读到的是窗口里的旧样本。
METRIC_STALE_SEC: Final[float] = 180.0
