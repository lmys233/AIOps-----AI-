"""Application contracts. Implementations are supplied by the composition root."""
from typing import Any, Protocol


class TaskPorts(Protocol):
    state_note: str
    def context(self, request, scope) -> Any: ...
    def context_result(self, body, context) -> dict: ...
    def bind_task(self, task, command) -> None: ...
    async def import_tasks(self, scope) -> list: ...
    async def choose(self, request, scope, tasks, foreground) -> tuple: ...
    async def prepare(self, repository, task, turn_id, usage, *, resume=False) -> Any: ...
    async def execute(self, request, task, command, extra, trace_id, usage, on_event, incident_id) -> dict: ...
    def refusal(self, request, trace_id, error) -> dict: ...
    def project(self, task, body) -> Any: ...
    def persisted_payload(self, request, body, details) -> dict: ...
    async def invalidate(self, session_id, body, *, annotate=True) -> None: ...
    async def cache_result(self, body) -> None: ...
    async def store_incident(self, body) -> None: ...
    async def answer_step(self, *args) -> dict: ...
    def render(self, *args, **kwargs) -> dict: ...
    async def settle_turn(self, *args) -> None: ...
